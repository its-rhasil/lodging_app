from datetime import datetime
from decimal import Decimal
from typing import Literal
from uuid import UUID

from pydantic import BaseModel, Field

PaymentMethod = Literal["cash", "upi", "card", "bank_transfer", "other"]
# numeric(12,2) in the ledger; requests are capped well below it.
Amount = Field(gt=0, max_digits=10, decimal_places=2)


class ChargeIn(BaseModel):
    """Service, restaurant, laundry, ... (not room charges: the engine posts those)."""
    amount: Decimal = Amount
    description: str = Field(min_length=1, max_length=200)


class PaymentIn(BaseModel):
    amount: Decimal = Amount
    method: PaymentMethod
    reference: str | None = Field(default=None, max_length=100)  # e.g. UPI transaction id
    # Generated by the screen once per submission. A double submit sends the same key.
    idempotency_key: UUID


class RefundIn(BaseModel):
    amount: Decimal = Amount
    method: PaymentMethod
    reference: str | None = Field(default=None, max_length=100)
    reason: str = Field(min_length=1, max_length=500)


class WaiveIn(BaseModel):
    amount: Decimal = Amount
    reason: str = Field(min_length=1, max_length=500)


class ReverseIn(BaseModel):
    reason: str = Field(min_length=1, max_length=500)


class TransactionOut(BaseModel):
    id: int
    txn_type: str
    direction: str
    amount: Decimal
    description: str | None
    period_no: int | None
    period_start_at: datetime | None
    payment_method: str | None
    reference: str | None
    related_txn_id: int | None
    reason: str | None
    created_by_user_id: int | None  # None = the system (posting engine)
    created_at: datetime
    is_reversed: bool
    waivable_amount: Decimal | None  # charges only: amount minus live waivers (0 once reversed)


class FolioOut(BaseModel):
    id: int
    stay_id: int
    status: str
    balance: Decimal  # > 0 the guest owes; < 0 the guest is in credit
    transactions: list[TransactionOut]
